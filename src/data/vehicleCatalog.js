const VEHICLE_CATALOG = {
  car: CAR,
  truck: TRUCK,
  motorcycle: MOTORCYCLE,
  trailer: TRAILER,
}

const sortedMakes = Object.fromEntries(
  Object.entries(VEHICLE_CATALOG).map(([type, makes]) => [type, Object.keys(makes).sort()]),
)

export const makesFor = (type) => sortedMakes[type] ?? sortedMakes.car

export function modelsFor(type, make) {
  const makes = VEHICLE_CATALOG[type] ?? VEHICLE_CATALOG.car
  const needle = String(make ?? '').trim().toLowerCase()
  if (!needle) return []

  const key = Object.keys(makes).find((name) => name.toLowerCase() === needle)
  return key ? makes[key] : []
}
